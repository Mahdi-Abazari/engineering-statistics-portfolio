"""Generate every numerical LaTeX macro from the Phase 2 results JSON."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
R = json.loads((ROOT / "reports" / "results.json").read_text(encoding="utf-8"))
DEST = ROOT / "reports" / "latex" / "values.tex"
DEST.parent.mkdir(parents=True, exist_ok=True)


def number(value, digits=3):
    if isinstance(value, int):
        return str(value)
    value = float(value)
    if value and abs(value) < .001:
        mantissa, exponent = f"{value:.2e}".split("e")
        return r"\ensuremath{%s\times10^{%s}}" % (mantissa, int(exponent))
    return f"{value:.{digits}f}"


def interval(pair, digits=3):
    return "[" + number(pair[0],digits) + ", " + number(pair[1],digits) + "]"


values = {}
def put(name, value):
    values[name] = str(value)


a = R["part_a"]
d = a["descriptive"]
for field,name in [("n","LifeN"),("mean","LifeMean"),("median","LifeMedian"),
                   ("sample_sd","LifeSD"),("minimum","LifeMin"),
                   ("maximum","LifeMax"),("cv","LifeCV")]:
    put(name,number(d[field]))
for field,name in [("theta_mom","ThetaMoM"),("theta_mle","ThetaMLE"),
                   ("mc_bias_trials","BiasTrials"),("mc_estimate_mean","MCMean"),
                   ("mc_bias","MCBias"),("mc_variance","MCVariance"),
                   ("theoretical_variance","TheoryVariance"),("crlb","CRLB"),
                   ("efficiency","Efficiency"),("consistency_trials_each","ConsistencyTrials"),
                   ("asymptotic_qq_r2","AsymptoticQQ"),
                   ("exact_width","ExactWidth"),("bootstrap_width","BootstrapWidth"),
                   ("data_bootstrap_resamples","BootData"),
                   ("reliability_500","Reliability")]:
    put(name,number(a[field]))
put("ThetaNumeric",number(a["theta_numeric_verify"]["estimate"]))
put("ExactCI",interval(a["exact_ci"]))
put("BootCI",interval(a["bootstrap_ci"]))
put("ReliabilityCI",interval(a["reliability_bootstrap_ci"]))
cov = a["coverage"]
for field,name in [("trials","CoverageTrials"),
                   ("bootstrap_resamples_per_trial","CoverageBoot"),
                   ("exact_coverage","ExactCoverage"),
                   ("bootstrap_coverage","BootCoverage")]:
    put(name,number(cov[field],4))
size_names = {10:"Ten",50:"Fifty",200:"TwoHundred",1000:"Thousand",5000:"FiveThousand"}
for row in a["consistency"]:
    suffix = size_names[row["n"]]
    put(f"VarEmp{suffix}",number(row["empirical_variance"]))
    put(f"VarTheory{suffix}",number(row["theoretical_variance"]))

b = R["part_b"]
fit = b["fit"]
for field,name in [("n","ProcessN"),("a","Intercept"),("b","Slope"),
                   ("xbar","TempMean"),("ybar","HardnessMean"),
                   ("sxx","Sxx"),("sxy","Sxy"),("syy","Syy"),
                   ("sse","SSE"),("s2","ErrorVariance"),
                   ("s","ResidualSE"),("r2","RSquared")]:
    put(name,number(fit[field],5 if field in ["b","r2"] else 3))
put("InterceptNumeric",number(b["gaussian_mle_numeric_verify"]["a"]))
put("SlopeNumeric",number(b["gaussian_mle_numeric_verify"]["b"],5))
put("SigmaMLE",number(b["gaussian_mle_numeric_verify"]["sigma2_mle"]))
inf = b["inference"]
for field,name in [("df","RegDF"),("t_critical","TCrit"),
                   ("se_a","InterceptSE"),("se_b","SlopeSE"),
                   ("slope_t","SlopeT"),("slope_p","SlopeP")]:
    put(name,number(inf[field],5 if field=="se_b" else 3))
put("InterceptCI",interval(inf["a_ci"]))
put("SlopeCI",interval(inf["b_ci"],5))
diag = b["diagnostics"]
for field,name in [("shapiro_w","ShapiroW"),("shapiro_p","ShapiroP"),
                   ("bp_lm","BPLM"),("bp_p","BPP"),
                   ("durbin_watson","DW")]:
    put(name,number(diag[field]))
pred = b["prediction_400"]
put("PredFourHundred",number(pred["mean_prediction"]))
put("MeanCI",interval(pred["mean_ci"]))
put("NewPartPI",interval(pred["prediction_interval"]))
put("TempMin",number(b["temperature_min"]))
put("TempMax",number(b["temperature_max"]))
regmc = b["monte_carlo"]
for field,name in [("trials","RegMCTrials"),("intercept_bias","RegInterceptBias"),
                   ("slope_bias","RegSlopeBias"),
                   ("slope_variance_empirical","RegSlopeVarEmp"),
                   ("slope_variance_theoretical","RegSlopeVarTheory"),
                   ("slope_ci_coverage","RegSlopeCoverage")]:
    put(name,number(regmc[field],5 if "slope" in field else 3))

DEST.write_text("% Generated by build_report.py; do not edit values by hand.\n" +
                "\n".join(r"\newcommand{\%s}{%s}" % (k,v) for k,v in values.items()) + "\n",
                encoding="utf-8")
print(f"Generated {DEST} with {len(values)} result macros")
