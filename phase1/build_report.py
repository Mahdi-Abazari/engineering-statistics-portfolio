"""Generate LaTeX numeric macros from the analysis JSON; never hand-edit results."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
R = json.loads((ROOT / "reports" / "results.json").read_text(encoding="utf-8"))
LATEX = ROOT / "reports" / "latex"
LATEX.mkdir(parents=True, exist_ok=True)


def num(x, digits=3):
    if isinstance(x, int):
        return str(x)
    if abs(x) < 0.001 and x != 0:
        return f"{x:.2e}"
    return f"{x:.{digits}f}"


def ci(v, digits=3):
    return f"[{num(v[0],digits)}, {num(v[1],digits)}]"


values = {}
def put(key, value):
    values[key] = str(value)


m1 = R["module1"]
put("SleepN", m1["n"])
put("ExcludedN", m1["middle_activity_excluded"])
labels = [("gender_stress", "GenderStress"), ("activity_steps", "ActivitySteps"),
          ("sleep_disorder", "SleepDisorder"), ("male_stress_activity", "MaleStress")]
for raw, label in labels:
    t = m1["tests"][raw]
    for field, key in [("n_a", "NA"), ("n_b", "NB"), ("statistic", "Statistic"),
                       ("p", "P"), ("holm_p", "HolmP"), ("effect", "Effect"),
                       ("shapiro_a", "ShapiroA"), ("shapiro_b", "ShapiroB"),
                       ("levene", "Levene")]:
        put(label+key, num(t[field]))
    put(label+"CI", ci(t["ci"]))
    put(label+"MeanA", num(t["mean_a"]))
    put(label+"MeanB", num(t["mean_b"]))
    if "df" in t:
        put(label+"DF", num(t["df"]))
o = R["module2"]
put("RejectFive", num(o["reject_at_5pct"],4))
put("AcceptTwo", num(o["accept_at_2pct"],4))
h = R["module3"]
for field, key in [("probability_175_195", "HeightProbability"),
                   ("sample_mean", "HeightMean"), ("sample_sd", "HeightSD"),
                   ("boxcox_lambda", "BoxLambda")]:
    put(key, num(h[field],4))
for index, label in enumerate(["Raw", "Log", "Box"]):
    put(label+"QQ", num(h["qq_r2"][index],6))
    put(label+"Shapiro", num(h["shapiro_p"][index],4))
p = R["module4"]
for field, key in [("n_a", "PrepNA"), ("n_b", "PrepNB"),
                   ("mean_a", "PrepMeanA"), ("mean_b", "PrepMeanB"),
                   ("sd_a", "PrepSDA"), ("sd_b", "PrepSDB"),
                   ("statistic", "PrepT"), ("df", "PrepDF"),
                   ("p", "PrepP"), ("effect", "PrepD"),
                   ("levene", "PrepLevene"), ("required_n_per_group", "PrepRequiredN")]:
    put(key, num(p[field]))
put("PrepCI", ci(p["ci"]))
c = R["module5"]
g = c["comparison"]
for field, key in [("n_a", "IndexNA"), ("n_b", "IndexNB"),
                   ("mean_a", "IndexMeanA"), ("mean_b", "IndexMeanB"),
                   ("statistic", "IndexT"), ("df", "IndexDF"),
                   ("p", "IndexP"), ("effect", "IndexD")]:
    put(key, num(g[field]))
put("IndexCI", ci(g["ci"]))
put("PearsonR", num(c["pearson_r"],4))
put("PearsonCI", ci(c["pearson_ci"],4))
put("SpearmanR", num(c["spearman_r"],4))
for subject, key in [("math score", "MathGap"), ("reading score", "ReadingGap"),
                     ("writing score", "WritingGap")]:
    put(key, num(c["subject_gap_female_minus_male"][subject]))

(LATEX / "values.tex").write_text("% Generated by build_report.py\n" +
    "\n".join(r"\newcommand{\%s}{%s}" % (k, v) for k,v in values.items()) + "\n", encoding="utf-8")
print(f"Generated {LATEX/'values.tex'} with {len(values)} results")
